// Прибираємо символи, які ламають синтаксис PostgREST .or() (кома,
// дужки, лапки) та ilike-джокери (% _).
function sanitize(word: string): string {
  return word.replace(/[,()"'%_*\\]/g, '').trim();
}

// Транслітерація суто російських особливостей у бік української.
// Кожне перетворення тут — надійне правило для запозичень:
//   подвоєні приголосні → одна (аккумулятор→акумулятор),
//   ы→и, э→е, ё→е, ъ→∅.
function transliterate(word: string): string {
  return word
    .replace(/([бвгджзклмнпрстфхцчшщ])\1/g, '$1') // подвоєні приголосні
    .replace(/ы/g, 'и')
    .replace(/э/g, 'е')
    .replace(/ё/g, 'е')
    .replace(/ъ/g, '');
}

// Переклад основи за словником — В ОБИДВА БОКИ (перше співпадіння
// за префіксом). Повертаємо обидві основи, БЕЗ закінчення слова:
// саме закінчення й ламало пошук — «килимки» не знаходило «килимок»,
// бо ilike шукав повне слово. Коротка основа «килим» знаходить обидва.
//
// Зворотний бік (укр. запит → рос. основа) майже нічого не додає в
// цьому каталозі (назви українські), але коштує один рядок і рятує
// поодинокі російські назви від постачальників.
function translateStem(word: string): [string, string] | null {
  for (const [ru, ua] of RU_UA_STEMS) {
    if (word.startsWith(ru)) return [ru, ua];
    if (word.startsWith(ua)) return [ua, ru];
  }
  return null;
}

// Для одного слова повертає всі варіанти пошуку (оригінал + переклади).
function variantsForWord(word: string): string[] {
  const out = new Set<string>();
  out.add(word);

  const stems = translateStem(word);
  if (stems) for (const st of stems) out.add(st);

  const tr = transliterate(word);
  if (tr !== word) out.add(tr);

  // Російська «и» у багатьох коренях відповідає українській «і»
  // (фильтр→фільтр, динамик→динамік). Додаємо як ще один варіант —
  // це лише розширює пошук (OR), хибних збігів практично не дає.
  const iVariant = word.replace(/и/g, 'і');
  if (iVariant !== word) out.add(iVariant);

  return [...out];
}

/**
 * Будує масив фільтрів для Supabase за пошуковим запитом.
 *
 * Кожен елемент — рядок для `.or(...)`: усередині слова через OR
 * перебираються і варіанти написання, і всі поля товару, а різні
 * слова додаються окремими `.or()` викликами — PostgREST поєднує
 * кілька `.or()` через AND. Тобто мають знайтись усі слова запиту
 * (у будь-якому написанні, у будь-якому полі), у будь-якому порядку.
 *
 * Приклади: "коврик в салон" → "Килимки в салон авто" (name),
 * "килимки toyota" → килимок із Toyota в compatibility.
 */
export function buildSearchFilters(raw: string): string[] {
  const words = raw
    .split(/\s+/)
    .map(sanitize)
    .filter((w) => w.length > 0);

  return words.map((word) => {
    const variants = variantsForWord(word);
    return variants
      .flatMap((v) => SEARCH_FIELDS.map((f) => `${f}.ilike.%${v}%`))
      .join(',');
  });
}
