// ─────────────────────────────────────────────────────────────
// Пошук: російська ↔ українська, по кількох полях товару.
//
// Назви товарів у базі — українською. Покупці шукають і російською
// («коврики»), і українською в іншій формі («килимки» замість
// «килимок»). Тому для кожного слова запиту будуємо набір варіантів
// (оригінал + основа + переклад в обидва боки + транслітерація) і
// шукаємо будь-який із них одразу в name, category, brand,
// compatibility, description.
// ─────────────────────────────────────────────────────────────

// Поля, по яких шукаємо. Назва — головне, але «Bosch» лежить у brand,
// «Toyota Camry» — у compatibility, «Передні фари» — у subcategory, а
// «Автохімія» взагалі тільки в category: у назвах товарів цих слів
// немає, і пошук по name давав нуль.
// description свідомо НЕ шукаємо. Заміри на живій базі: він додає 0,05%
// результатів («килимки» 28971 → 28978), але коштує ~250 мс на кожному запиті
// і, головне, ламає індекси: OR по неіндексованому полю змушує базу читати
// всю таблицю, і GIN-індекси на решті полів стають марними.
const SEARCH_FIELDS = ['name', 'category', 'subcategory', 'brand', 'compatibility'];

// Словник російських основ (стемів) → українські основи.
